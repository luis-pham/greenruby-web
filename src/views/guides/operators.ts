//   pages disagree, the range covers both and `note` says so.
// - confirmed = published on the operator's own website and consistent; indicative = operator site with
//   internal conflicts, or a reputable booking platform only; unverified = not shown on the page.
// - `listed: false` keeps a researched entry out of the tables (reason in `note`), so the next review
//   doesn't redo the same research.
