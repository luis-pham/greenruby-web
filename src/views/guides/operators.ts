export const operatorById = (id: string) => OPERATORS.find((o) => o.operatorId === id);

/** Services shown to readers for the given routes, in registry order. */
export function listedServices(routes: readonly RouteId[]): Service[] {
  return SERVICES.filter((s) => s.listed && s.verificationStatus !== 'unverified' && routes.includes(s.routeId));
}

/** open: at least one price is a "from" price with no upper bound. */
export type FareRange = { transportType: TransportType; min: number; max: number; currency: 'VND' | 'USD'; unit: 'seat' | 'vehicle'; open: boolean };

const TYPE_ORDER: TransportType[] = ['shared-limousine', 'bus', 'private-car'];

/**
 * Published fare ranges for a route, per transport type, currency and unit. Includes price-reference
 * entries that are not listed in the tables, but never unverified ones.
 */
export function fareRanges(route: RouteId): FareRange[] {
  const out: FareRange[] = [];
  for (const s of SERVICES) {
    if (s.routeId !== route || s.verificationStatus === 'unverified' || s.fareMin === null) continue;
    const max = s.fareMax ?? s.fareMin;
    const r = out.find((x) => x.transportType === s.transportType && x.currency === s.fareCurrency && x.unit === s.fareUnit);
    if (r) {
      r.min = Math.min(r.min, s.fareMin);
      r.max = Math.max(r.max, max);
      r.open ||= s.fareMax === null;
    } else {
      out.push({ transportType: s.transportType, min: s.fareMin, max, currency: s.fareCurrency, unit: s.fareUnit, open: s.fareMax === null });
    }
  }
  return out.sort((a, b) => TYPE_ORDER.indexOf(a.transportType) - TYPE_ORDER.indexOf(b.transportType) || (a.currency === 'VND' ? -1 : 1));
}
