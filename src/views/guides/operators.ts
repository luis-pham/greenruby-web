export type Area = 'hanoi' | 'noibai' | 'ninhbinh' | 'catbi' | 'vandon' | 'halong';
export type RouteId = `${Exclude<Area, 'halong'>}-halong` | `halong-${Exclude<Area, 'halong'>}`;
/** Text in both languages; place and brand names stay as they are. */
export type L = { en: string; vi: string };
export type VerificationStatus = 'confirmed' | 'indicative' | 'unverified';
export type TransportType = 'shared-limousine' | 'bus' | 'private-car';
/** How the service handles Tuan Chau: door (drops/collects at the port), stop (fixed stop in the Tuan Chau area), ask (not stated), no (Bai Chay or elsewhere only). */
export type TuanChau = 'door' | 'stop' | 'ask' | 'no';

export type Phone = {
  display: string;
  /** Digits with country code, for tel:/wa.me. Absent for 1900 numbers, which only work inside Vietnam. */
  e164?: string;
  whatsapp?: boolean;
  zalo?: boolean;
};

export type Operator = {
  operatorId: string;
  operatorName: string;
  website?: string;
  phones: Phone[];
};

export type Service = {
  operatorId: string;
  routeId: RouteId;
  transportType: TransportType;
  vehicle: L;
  pickupLocations: L;
  dropoffLocations: L;
  tuanChau: TuanChau;
  fareMin: number | null;
  fareMax: number | null;
  fareCurrency: 'VND' | 'USD';
  fareUnit: 'seat' | 'vehicle';
  departureTimes: L | null;
  estimatedDuration: L | null;
  luggage?: L;
  /** Where to book. For agent-only listings this is the platform page. */
  bookingUrl?: string;
  sourceUrls: string[];
  sourceType: 'operator' | 'agent';
  verifiedAt: string;
  verificationStatus: VerificationStatus;
  listed: boolean;
  note?: L;
};

