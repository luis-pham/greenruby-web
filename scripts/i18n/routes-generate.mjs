#!/usr/bin/env node
// Generates the intl route trees (phase 1D-b, docs/i18n-audit/phase-1/1d-b-report.md) and the route registry.
//
//   node scripts/i18n/routes-generate.mjs           write src/app/(<code>)/<code>/… and src/lib/routes.generated.ts
//   node scripts/i18n/routes-generate.mjs --check   exit 1 when either is out of date (run by `npm test`)
//
// For every compiled intl locale (src/lib/i18n.ts `locales` minus en/vi) it copies the English route shims of the
// intl sections (src/lib/intl-routes.ts) under /(code)/code with the English segments, each wrapped in intlRoute()
// (src/lib/intl-route.tsx). Static (ja)/ja/… trees, not a [lang] segment: a shared dynamic segment changes EN 404s
// and leaks draft data into the 404 RSC payload (docs/i18n-audit/13). Adding a language = add it to `locales`, run this.
// The registry lists every page route that exists on disk, so the manifest reports routes, not configuration.

import { existsSync, mkdirSync, readdirSync, readFileSync, rmdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const app = join(root, 'src', 'app');
const registryFile = join(root, 'src', 'lib', 'routes.generated.ts');
const { locales, isLegacyLocale } = await import(join(root, 'src', 'lib', 'i18n.ts'));
const { intlRequirements, hubRoutes } = await import(join(root, 'src', 'lib', 'intl-routes.ts'));

const MARK = '// GENERATED by scripts/i18n/routes-generate.mjs';
const check = process.argv.includes('--check');
const posix = (p) => p.split(sep).join('/');

/** Every page route key on disk: '/(en)/cruise/[file]', '/(en)' … */
function scan(dir = app) {
  const keys = [];
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) {
      if (dir === app && name === 'api') continue;
      keys.push(...scan(path));
    } else if (/^page\.(tsx|ts|jsx|js)$/.test(name)) {
      keys.push(`/${posix(relative(app, dir))}`);
    }
  }
  return keys;
}

function shim(code, section, route) {
  const sourcePath = join(app, '(en)', route, 'page.tsx');
  const source = readFileSync(sourcePath, 'utf8');
  const imports = [...source.matchAll(/^import \{ (\w+) \} from '(@\/views\/[^']+)';$/gm)];
  const call = /^const route = (\w+)\('en'\);$/m.exec(source);
  if (imports.length !== 1 || !call || call[1] !== imports[0][1]) {
    throw new Error(`${posix(relative(root, sourcePath))}: expected one view import and "const route = <factory>('en');"`);
  }
  const exportsList = [...source.matchAll(/^export (?:const (\w+) = route\.(\w+)|default route\.(\w+));$/gm)].map((m) =>
    m[3] ? `export default route.${m[3]};` : `export const ${m[1]} = route.${m[2]};`,
  );
  const params = [...route.matchAll(/\[(\[)?(\.\.\.)?(\w+)\]?\]/g)].map((m) => `${m[3]}: ${m[2] ? "['_']" : "'_'"}`);
  const options = [`locale: '${code}'`, `section: '${section}'`, `hub: ${route in hubRoutes}`];
  if (params.length) options.push(`placeholder: { ${params.join(', ')} }`);
  return `${MARK} from src/app/(en)/${route ? `${route}/` : ''}page.tsx. Do not edit.
import { intlRoute } from '@/lib/intl-route';
import { ${call[1]} } from '${imports[0][2]}';

// Prerendered; navigations wait for the page so 404/301 status codes stay correct (a closed locale is a 404).
export const ensureStatic = 'navigation';
export const instant = false;

const route = intlRoute({ ${options.join(', ')} }, ${call[1]}('${code}'));
${exportsList.join('\n')}
`;
}

function plan() {
  const files = new Map();
  const enKeys = scan().filter((key) => key === '/(en)' || key.startsWith('/(en)/'));
  for (const code of locales.filter((l) => !isLegacyLocale(l))) {
    const group = join(app, `(${code})`);
    files.set(join(group, 'layout.tsx'), `${MARK}. Do not edit.
import type { Metadata } from 'next';
import type { ReactNode } from 'react';
import { RootDocument } from '@/components/layout/RootDocument';
import { siteUrl } from '@/lib/site-url';

export const metadata: Metadata = { metadataBase: new URL(siteUrl) };

export default function RootLayout({ children }: { children: ReactNode }) {
  return <RootDocument locale="${code}">{children}</RootDocument>;
}
`);
    files.set(join(group, 'not-found.tsx'), `${MARK}. Do not edit.
import { NotFoundView } from '@/views/not-found/NotFoundView';

export default function NotFound() {
  return <NotFoundView locale="${code}" />;
}
`);
    for (const [section, routes] of intlRequirements(enKeys)) {
      for (const route of routes) files.set(join(group, code, route, 'page.tsx'), shim(code, section, route));
    }
  }
  return files;
}

/** Generated files on disk that the plan no longer contains (a removed language or route). */
function stale(files) {
  const out = [];
  const walk = (dir) => {
    for (const name of readdirSync(dir)) {
      const path = join(dir, name);
      if (statSync(path).isDirectory()) walk(path);
      else if (!files.has(path) && readFileSync(path, 'utf8').startsWith(MARK)) out.push(path);
    }
  };
  for (const name of readdirSync(app)) {
    const code = /^\(([a-z]{2,3}(?:-[a-z0-9]+)*)\)$/i.exec(name)?.[1];
    if (code && !isLegacyLocale(code)) walk(join(app, name));
  }
  return out;
}

function registry(keys) {
  return `${MARK}: every page route under src/app (route groups included). Do not edit.
// Read by the readiness manifest and the intl route gate (src/lib/intl-routes.ts); \`npm test\` checks it is current.
export const appRoutes: readonly string[] = [
${[...new Set(keys)].sort().map((key) => `  '${key}',`).join('\n')}
];
`;
}

const files = plan();
const remove = stale(files);
const changed = [...files].filter(([path, text]) => !existsSync(path) || readFileSync(path, 'utf8') !== text).map(([path]) => path);
const diskKeys = scan().filter((key) => !remove.some((path) => `/${posix(relative(app, dirname(path)))}` === key));
const plannedKeys = [...files.keys()].filter((path) => path.endsWith(`${sep}page.tsx`)).map((path) => `/${posix(relative(app, dirname(path)))}`);
const registryText = registry([...diskKeys, ...plannedKeys]);
const registryStale = !existsSync(registryFile) || readFileSync(registryFile, 'utf8') !== registryText;

if (check) {
  const problems = [...changed.map((p) => `out of date: ${posix(relative(root, p))}`), ...remove.map((p) => `stale: ${posix(relative(root, p))}`)];
  if (registryStale) problems.push(`out of date: ${posix(relative(root, registryFile))}`);
  if (problems.length) {
    console.error(`${problems.join('\n')}\nRun: node scripts/i18n/routes-generate.mjs`);
    process.exit(1);
  }
  console.log(`routes up to date (${files.size} generated files)`);
} else {
  for (const path of changed) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, files.get(path));
  }
  for (const path of remove) {
    rmSync(path);
    for (let dir = dirname(path); dir !== app && readdirSync(dir).length === 0; dir = dirname(dir)) rmdirSync(dir);
  }
  if (registryStale) writeFileSync(registryFile, registryText);
  console.log(`${changed.length} written, ${remove.length} removed, registry ${registryStale ? 'updated' : 'unchanged'} (${files.size} generated files)`);
}
