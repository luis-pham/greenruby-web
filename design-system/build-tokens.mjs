// Build tokens.json (DTCG) -> tokens.css (CSS custom properties) + tokens.ts (resolved values).
// Zero dependencies. Usage: node design-system/build-tokens.mjs [outDir]
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const outDir = process.argv[2] ?? join(here, '..', 'src', 'styles');
const tree = JSON.parse(readFileSync(join(here, 'tokens.json'), 'utf8'));

// Flatten to [{ path: ['color','green','900'], value, type }]
const tokens = [];
(function walk(node, path, inheritedType) {
  const type = node.$type ?? inheritedType;
  if ('$value' in node) {
    tokens.push({ path, value: node.$value, type });
    return;
  }
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith('$') || typeof child !== 'object') continue;
    walk(child, [...path, key], type);
  }
})(tree, [], undefined);

// "semantic.text.body" is exposed as --text-body; everything else keeps its full path.
const cssName = (path) => '--' + (path[0] === 'semantic' ? path.slice(1) : path).join('-');
const byPath = new Map(tokens.map((t) => [t.path.join('.'), t]));

function format(value, type) {
  if (type === 'fontFamily') return value.map((f) => (f.includes(' ') ? `"${f}"` : f)).join(', ');
  if (type === 'cubicBezier') return `cubic-bezier(${value.join(', ')})`;
  return String(value);
}

function toCss(t) {
  if (typeof t.value === 'string' && /^\{.+\}$/.test(t.value)) {
    const ref = byPath.get(t.value.slice(1, -1));
    if (!ref) throw new Error(`Unresolved reference ${t.value} in ${t.path.join('.')}`);
    return `var(${cssName(ref.path)})`;
  }
  return format(t.value, t.type);
}

function resolve(t, seen = new Set()) {
  if (typeof t.value === 'string' && /^\{.+\}$/.test(t.value)) {
    const key = t.value.slice(1, -1);
    if (seen.has(key)) throw new Error(`Circular reference at ${key}`);
    seen.add(key);
    return resolve(byPath.get(key), seen);
  }
  return format(t.value, t.type);
}

// Breakpoints can't be used inside @media via var(); they're emitted as comments + TS only.
const cssTokens = tokens.filter((t) => t.path[0] !== 'breakpoint');
const breakpoints = tokens.filter((t) => t.path[0] === 'breakpoint');

const css = [
  '/* GENERATED by design-system/build-tokens.mjs from tokens.json — do not edit by hand. */',
  '/* Breakpoints (max-width): ' + breakpoints.map((t) => `${t.path[1]}=${t.value}`).join(', ') + ' */',
  ':root {',
  ...cssTokens.map((t) => `  ${cssName(t.path)}: ${toCss(t)};`),
  '}',
  '',
].join('\n');

// Nested, fully resolved object for TS consumers (next/image sizes, JSON-LD colors, OG images).
const resolved = {};
for (const t of tokens) {
  const path = t.path[0] === 'semantic' ? t.path.slice(1) : t.path;
  let node = resolved;
  path.slice(0, -1).forEach((k) => (node = node[k] ??= {}));
  node[path.at(-1)] = resolve(t);
}
const ts = [
  '// GENERATED by design-system/build-tokens.mjs from tokens.json — do not edit by hand.',
  `export const tokens = ${JSON.stringify(resolved, null, 2)} as const;`,
  '',
  'export const breakpoints = {',
  ...breakpoints.map((t) => `  ${t.path[1]}: ${parseInt(t.value, 10)},`),
  '} as const;',
  '',
].join('\n');

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'tokens.css'), css);
writeFileSync(join(outDir, 'tokens.ts'), ts);
console.log(`tokens: ${tokens.length} -> ${join(outDir, 'tokens.css')}, tokens.ts`);
